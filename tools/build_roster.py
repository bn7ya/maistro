#!/usr/bin/env python3
"""Regenerate the parts of the plugin that are derived from other files.

- The roster table in skills/lab-protocol/SKILL.md (from the agent files)
- The generated block in workflows/lab-stage.js: ROSTER (from the agent files),
  POLICY (scripts/source-policy.json) and K (scripts/lab-constants.json)
- scripts/roster.json (the roster, for the Python scripts)

Usage: python3 tools/build_roster.py [--check]
With --check nothing is written; the exit code is 1 if anything is out of date.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "maistro"
AGENTS = PLUGIN / "agents"
SKILL = PLUGIN / "skills" / "lab-protocol" / "SKILL.md"
WORKFLOW = PLUGIN / "workflows" / "lab-stage.js"
POLICY = PLUGIN / "scripts" / "source-policy.json"
CONSTANTS = PLUGIN / "scripts" / "lab-constants.json"
ROSTER_JSON = PLUGIN / "scripts" / "roster.json"

DIVISIONS = ["director", "methodology", "sources", "theory", "experiments", "critique", "frontier", "editorial"]
DIVISION_TITLES = {
    "director": "Director",
    "methodology": "Methodology",
    "sources": "Source integrity",
    "theory": "Theory",
    "experiments": "Test engineering",
    "critique": "Critique",
    "frontier": "Frontier (speculative)",
    "editorial": "Editorial",
}


def parse_frontmatter(text):
    """Minimal YAML frontmatter reader for the flat keys our agent files use."""
    if not text.startswith("---\n"):
        raise ValueError("missing frontmatter")
    end = text.index("\n---", 4)
    fm, body = text[4:end], text[end + 4:].lstrip("\n")
    data, key = {}, None
    for line in fm.splitlines():
        if not line.strip():
            continue
        m = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            data[key] = val if val else []
        elif line.strip().startswith("- ") and key is not None:
            if not isinstance(data[key], list):
                data[key] = []
            data[key].append(line.strip()[2:].strip())
    return data, body


def load_agents():
    agents = []
    for path in sorted(AGENTS.rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        fm, body = parse_frontmatter(text)
        rel = path.relative_to(AGENTS)
        division = rel.parts[0] if len(rel.parts) > 1 else "director"
        name = fm.get("name") or path.stem
        agent_id = name.split("-", 1)[0].upper()
        h1 = re.search(r"^# (\S+) · (.+)$", body, re.M)
        mission = re.search(r"^> (.+)$", body, re.M)
        scope = ":".join(["maistro"] + list(rel.parts[:-1]) + [name])
        agents.append({
            "id": agent_id,
            "type": scope,
            "division": division,
            "title": h1.group(2).strip() if h1 else name,
            "h1_id": h1.group(1) if h1 else None,
            "mission": mission.group(1).strip() if mission else "",
            "model": fm.get("model"),
            "frontmatter": fm,
            "body": body,
            "path": path,
        })
    agents.sort(key=lambda a: (DIVISIONS.index(a["division"]) if a["division"] in DIVISIONS else 99, a["id"]))
    return agents


def roster_markdown(agents):
    out = ["<!-- roster:begin (generated by tools/build_roster.py; do not edit by hand) -->"]
    for div in DIVISIONS:
        members = [a for a in agents if a["division"] == div]
        if not members:
            continue
        out.append("")
        out.append(f"**{DIVISION_TITLES[div]}** (`division:{div}`)")
        out.append("")
        out.append("| ID | Role | Contribution |")
        out.append("|---|---|---|")
        for a in members:
            out.append(f"| {a['id']} | {a['title']} | {a['mission']} |")
    out.append("<!-- roster:end -->")
    return "\n".join(out)


def generated_js(agents):
    roster = [{"id": a["id"], "type": a["type"], "division": a["division"], "title": a["title"]} for a in agents]
    policy = json.loads(POLICY.read_text(encoding="utf-8"))
    consts = json.loads(CONSTANTS.read_text(encoding="utf-8"))
    lines = ["// <generated:begin>", "const ROSTER = ["]
    for r in roster:
        lines.append("  " + json.dumps(r, ensure_ascii=False) + ",")
    lines.append("]")
    lines.append("const POLICY = " + json.dumps(policy, ensure_ascii=False))
    lines.append("const K = " + json.dumps(consts, ensure_ascii=False))
    lines.append("// <generated:end>")
    return "\n".join(lines)


def replace_block(text, begin, end, new):
    i, j = text.index(begin), text.index(end)
    j = text.index("\n", j) if "\n" in text[j:] else len(text)
    return text[:i] + new + text[j:]


def main():
    check = "--check" in sys.argv
    agents = load_agents()
    skill_old = SKILL.read_text(encoding="utf-8")
    skill_new = replace_block(skill_old, "<!-- roster:begin", "<!-- roster:end -->", roster_markdown(agents))
    wf_old = WORKFLOW.read_text(encoding="utf-8")
    wf_new = replace_block(wf_old, "// <generated:begin>", "// <generated:end>", generated_js(agents))
    roster_old = ROSTER_JSON.read_text(encoding="utf-8") if ROSTER_JSON.exists() else ""
    roster_new = json.dumps([{"id": a["id"], "type": a["type"], "division": a["division"], "title": a["title"]} for a in agents],
                            ensure_ascii=False, indent=1) + "\n"
    stale = [p for p, old, new in ((SKILL, skill_old, skill_new), (WORKFLOW, wf_old, wf_new), (ROSTER_JSON, roster_old, roster_new)) if old != new]
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        if stale:
            print("run: python3 tools/build_roster.py")
        return 1 if stale else 0
    SKILL.write_text(skill_new, encoding="utf-8")
    WORKFLOW.write_text(wf_new, encoding="utf-8")
    ROSTER_JSON.write_text(roster_new, encoding="utf-8")
    counts = {}
    for a in agents:
        counts[a["division"]] = counts.get(a["division"], 0) + 1
    print(f"{len(agents)} agents: " + ", ".join(f"{d} {counts.get(d, 0)}" for d in DIVISIONS))
    for p in stale:
        print(f"updated {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
